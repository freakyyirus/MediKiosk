const DICTS: Record<KioskLang, Record<KioskKey, string>> = {
  en, hi, bn, te, mr, ta, gu, kn, ml, pa, or, as, ur,
};

export function langCodeToKiosk(code: string): KioskLang {
  return (DICTS[code as KioskLang] ? (code as KioskLang) : 'en');
}

export function kt(code: string, key: KioskKey, vars?: Record<string, string | number>): string {
  const lang = langCodeToKiosk(code);
  let out = DICTS[lang][key] ?? DICTS.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      out = out.split(`{${k}}`).join(String(v));
    }
  }
  return out;
}