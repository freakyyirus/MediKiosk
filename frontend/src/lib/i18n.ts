const DICTS: Record<LangCode, Dict> = { en, hi, ta, bn, mr };

export function t(key: DictKey, lang: LangCode, vars?: Record<string, string | number>): string {
  const dict = DICTS[lang] ?? DICTS.en;
  let s: string = dict[key] ?? DICTS.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.split(`{${k}}`).join(String(v));
    }
  }
  return s;
}

/** Reactive hook — re-renders when the UI language changes. */
export function useT() {
  const lang = useUIStore((s) => s.language);
  const code: LangCode = (['en', 'hi', 'ta', 'bn', 'mr'] as LangCode[]).includes(lang.code as LangCode)
    ? (lang.code as LangCode)
    : 'en';
  return (key: DictKey, vars?: Record<string, string | number>) => t(key, code, vars);
}

