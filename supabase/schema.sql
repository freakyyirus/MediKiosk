-- ============================================================================
-- 4. ROW-LEVEL SECURITY
-- ============================================================================
-- Policy model:
--   * The backend runs with the SERVICE_ROLE key -> bypasses RLS entirely,
--     so it can read/write everything it needs.
--   * The anonymous (anon) key is used by the public kiosk ONLY to write
--     consent records and messages via the backend. To keep it safe we still
--     enable RLS and grant the anon role nothing by default — the backend is
--     the only writer. Admin can relax per-table policies later if the
--     frontend must query directly (not recommended for PHI).

ALTER TABLE public.patients           ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sessions           ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.session_messages   ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.documents          ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.summaries          ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.consent_records    ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.red_flag_alerts    ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.audit_logs         ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ayush_assessments  ENABLE ROW LEVEL SECURITY;

-- Drop default grants so anon cannot touch tables by default (defense in depth).
REVOKE ALL ON public.patients, public.sessions, public.session_messages,
    public.documents, public.summaries, public.consent_records,
    public.red_flag_alerts, public.audit_logs, public.ayush_assessments
    FROM anon, authenticated;

-- The backend (service_role) already bypasses RLS. For completeness, grant it
-- full DML — redundant but explicit.
GRANT SELECT, INSERT, UPDATE, DELETE ON
    public.patients, public.sessions, public.session_messages,
    public.documents, public.summaries, public.consent_records,
    public.red_flag_alerts, public.audit_logs, public.ayush_assessments
    TO service_role;

-- Sequences must be usable by service_role for IDENTITY inserts to work.
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;

